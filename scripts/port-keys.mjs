#!/usr/bin/env node
/* scripts/port-keys.mjs — regenerate electron/backend/updater-keys.js.

   `PORT_UPDATER_PUBKEY` (base64 of the whole minisign.pub text, as printed
   by scripts/port-feed.mjs) bakes the fork's release identity into the
   build; without it the module keeps the upstream identity so dev runs and
   the test suite stay on the Tauri feed. Run by `npm run port:build`. */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const key = process.env.PORT_UPDATER_PUBKEY ?? "";
const out = join(here, "..", "electron", "backend", "updater-keys.js");
writeFileSync(out, `/* generated by scripts/port-keys.mjs — do not hand-edit */
"use strict";

module.exports = {
  publicKey: ${JSON.stringify(key)},
  feed: "",
};
`);
console.log(`port-keys: ${key ? "fork identity baked in" : "upstream identity (no PORT_UPDATER_PUBKEY)"}`);
